export type ProductStatus = 'active' | 'inactive'

export interface Product {
  id?: number // optional: generated by the database on create
  name: string
  sku: string
  category: string
  price: number
  quantity: number
  status: ProductStatus
  createdAt: number
  updatedAt: number
}

// Form input: excludes id and timestamps, which the system sets
export type ProductInput = Omit<Product, 'id' | 'createdAt' | 'updatedAt'>

export type Role = 'admin' | 'user'

// User record as stored in the database (includes password hash)
export interface User {
  id?: number
  name: string
  email: string
  passwordHash: string
  role: Role
}

// User object used inside the app (never includes the password hash)
export interface SessionUser {
  id: number
  name: string
  email: string
  role: Role
}
